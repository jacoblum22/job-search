@needs_pg
def test_cutover_backup_and_rollback(jobs_db, pg, schema, tmp_path, monkeypatch):
    env = tmp_path / ".env"
    env.write_text("JOBSEARCH_PG_URL=whatever\n")
    backups = tmp_path / "backups"
    want = sqlite3.connect(jobs_db).execute("SELECT * FROM jobs ORDER BY id").fetchall()

    out = pg_cutover.run_cutover(jobs_db, pg, env_path=env, backups_dir=backups)
    assert all(r["match"] for r in out["report"].values())
    assert out["copied"]["jobs"] == 4
    assert not jobs_db.exists() and (backups / out["moved_to"].split("/")[-1].split("\\")[-1]).exists()
    assert "JOBSEARCH_DB=postgres" in env.read_text()
    # The mirror's hash column is gone and new ids continue after SQLite's highest (5).
    assert pg_mirror.HASH_COL not in pg_cutover._pg_columns(pg, "jobs")
    monkeypatch.setenv("JOBSEARCH_DB", "postgres")
    monkeypatch.setenv("JOBSEARCH_PG_URL", _url(schema))
    conn = connect(db.MAIN_DB)
    assert upsert_job(conn, _job(9)) == (6, True)
    assert conn.execute("SELECT status FROM jobs WHERE id = 6").fetchone()[0] == "new"
    conn.commit()
    conn.close()
    monkeypatch.setenv("JOBSEARCH_DB", "sqlite")

    path, counts = pg_cutover.backup(pg, backups, keep=2, today="2026-10-28")
    assert counts["jobs"] == 5 and path.name == "jobs-2026-10-28.db"
    pg_cutover.backup(pg, backups, keep=2, today="2026-10-29")
    pg_cutover.backup(pg, backups, keep=2, today="2026-10-30")
    assert sorted(p.name for p in backups.glob("jobs-20*.db")) == ["jobs-2026-10-29.db", "jobs-2026-10-30.db"]
    assert pg_cutover.latest_backup(backups).name == "jobs-2026-10-30.db"

    back = pg_cutover.run_rollback(pg, jobs_db, env_path=env, backups_dir=backups)
    assert back["restored"]["jobs"] == 5 and "jobs" in back["set_aside"]
    assert "JOBSEARCH_DB" not in env.read_text()
    lite = connect(jobs_db)
    assert [tuple(r) for r in lite.execute("SELECT * FROM jobs WHERE id < 6 ORDER BY id")] == \
        [tuple(r) for r in want]
    # SQLite carries on from Postgres's ids, and the app writes it as before.
    assert upsert_job(lite, _job(10)) == (7, True)
    lite.commit()
    lite.close()
    # The mirror can start over against the restored jobs.db.
    stats = pg_mirror.sync(jobs_db, pg)
    assert stats["jobs"]["inserted"] == 6
    assert all(r["match"] for r in pg_mirror.check(jobs_db, pg).values())


@needs_pg
def test_cutover_stops_when_jobs_db_changes(jobs_db, pg, tmp_path, monkeypatch):
    env = tmp_path / ".env"
    env.write_text("")
    real = pg_cutover.verify

    def verify_then_write(path, conn):
        out = real(path, conn)
        lite = sqlite3.connect(path)
        lite.execute("UPDATE jobs SET status = 'applied' WHERE id = 2")
        lite.commit()
        lite.close()
        return out

    monkeypatch.setattr(pg_cutover, "verify", verify_then_write)
    with pytest.raises(pg_cutover.CutoverError, match="changed during the copy"):
        pg_cutover.run_cutover(jobs_db, pg, env_path=env, backups_dir=tmp_path / "b")
    assert jobs_db.exists() and "JOBSEARCH_DB" not in env.read_text()
    assert pg_cutover._pg_tables(pg) == []  # the next mirror sync starts clean


