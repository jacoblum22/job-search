def _job(n: int, **kw) -> Job:
    return Job(source="greenhouse", external_id=str(n), title=f"Data Analyst {n}", company="Acme",
               location="Vancouver, BC", description=kw.pop("description", "Python and SQL."),
               raw={"n": n}, **kw)


@needs_pg
def test_app_code_runs_on_postgres(live):
    assert db.is_postgres(live)
    assert upsert_job(live, _job(1)) == (1, True)
    assert upsert_job(live, _job(2, description="Python, SQL and dbt\x00 every day.")) == (2, True)
    # Seen again: same id, longer description kept.
    assert upsert_job(live, _job(1, description="short")) == (1, False)
    assert live.execute("SELECT description FROM jobs WHERE id = 1").fetchone()["description"] == "Python and SQL."
    assert "\x00" not in live.execute("SELECT description FROM jobs WHERE id = 2").fetchone()[0]
    live.commit()

    db.set_cursor(live, "gmail", "123")
    db.set_cursor(live, "gmail", "456")
    assert db.get_cursor(live, "gmail") == "456"
    assert set_job_status(live, 2, "dismissed") == 1
    groups = grouped_jobs(live)
    assert [g["id"] for g in groups] == [2, 1] or {g["id"] for g in groups} == {1, 2}
    assert db.has_table(live, "applications") and "score_reasons" in db.table_columns(live, "jobs")

    store.upsert_app(live, {"job_id": 1, "status": "ready_for_review", "score": 71.8,
                            "gate": {"flags": ["years"]}}, store.ROOT / "materials" / "applications" / "x")
    store.set_status(live, 1, "approved", outcome="interview")
    app = store.get_app(live, 1)
    assert app["status"] == "approved" and app["gate_flags"] == ["years"] and app["score"] == 71.8
    assert set(store.all_apps(live)) == {1}

    # Retention: tombstones with INSERT OR IGNORE, twice without error; jobs with an
    # application are kept.
    assert delete_expired(live, {("greenhouse", "1"), ("greenhouse", "2"), ("lever", "gone")}) == 1
    assert delete_expired(live, {("lever", "gone")}) == 0
    live.commit()
    assert ("lever", "gone") in pruned_keys(live)
    assert prune(live, 30) == 0
    assert [r[0] for r in live.execute("SELECT id FROM jobs")] == [1]


