def test_translate_placeholders_and_sqlite_only_syntax():
    assert translate("SELECT * FROM jobs WHERE id = ? AND source = ?") == \
        "SELECT * FROM jobs WHERE id = %s AND source = %s"
    assert translate("UPDATE applications SET status = :status WHERE job_id = :job_id") == \
        "UPDATE applications SET status = %(status)s WHERE job_id = %(job_id)s"
    # Quoted text is left alone, but a literal % is doubled for psycopg.
    assert translate("SELECT '?:x 5%' WHERE a = ?") == "SELECT '?:x 5%%' WHERE a = %s"
    assert translate("SELECT 'it''s ?' , ?") == "SELECT 'it''s ?' , %s"
    assert translate("SELECT 5 % 2", has_params=False) == "SELECT 5 % 2"
    assert translate("SELECT x::text WHERE y = ?") == "SELECT x::text WHERE y = %s"
    assert translate("INSERT OR IGNORE INTO pruned_jobs (a) VALUES (?)") == \
        "INSERT INTO pruned_jobs (a) VALUES (%s) ON CONFLICT DO NOTHING"
    assert "chr(10)" in translate("SELECT replace(d, char(10), '') FROM jobs")
    with pytest.raises(NotImplementedError):
        translate("PRAGMA table_info(jobs)")


def test_translate_ddl_types():
    sql = translate("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER, s REAL, x TEXT)",
                    has_params=False)
    assert sql == ("CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                   "n BIGINT, s DOUBLE PRECISION, x TEXT)")
    assert translate("ALTER TABLE jobs ADD COLUMN score INTEGER", has_params=False).endswith("BIGINT")
    # Only DDL has its types rewritten.
    assert translate("SELECT 'INTEGER'", has_params=False) == "SELECT 'INTEGER'"


def test_row_reads_like_sqlite_row():
    r = Row({"id": 0, "title": 1}, (7, "Analyst"))
    assert r[0] == 7 and r["title"] == "Analyst" and r[-1] == "Analyst"
    assert dict(r) == {"id": 7, "title": "Analyst"}
    a, b = r
    assert (a, b) == (7, "Analyst") and len(r) == 2 and r.keys() == ["id", "title"]


def test_main_db_follows_the_setting(tmp_path, monkeypatch):
    monkeypatch.setenv("JOBSEARCH_DB", "sqlite")
    assert db.backend() == "sqlite"
    monkeypatch.setenv("JOBSEARCH_DB", "postgres")
    assert db.backend() == "postgres"
    monkeypatch.delenv("JOBSEARCH_PG_URL", raising=False)
    monkeypatch.setattr(db, "ROOT", tmp_path)  # no .env there
    with pytest.raises(RuntimeError, match="JOBSEARCH_PG_URL"):
        connect(db.MAIN_DB)
    # Any other path is still a SQLite file.
    conn = connect(tmp_path / "other.db")
    assert isinstance(conn, sqlite3.Connection)
    conn.close()


