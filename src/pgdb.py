"""Postgres behind the sqlite3 interface the rest of the code already uses (Azure plan, phase 4).

`src.db.connect` returns a `PgConnection` instead of a sqlite3 connection once the main
database lives in Postgres (docs/postgres-mirror.md, "Phase 4"). It accepts what the code
sends SQLite: `?` and `:name` placeholders, `INSERT OR IGNORE`, `char(10)`, and the
SQLite DDL in each module's SCHEMA (INTEGER PRIMARY KEY AUTOINCREMENT, INTEGER, REAL).
Rows act like sqlite3.Row (by position, by name, `dict(row)`).

Anything SQLite-only that isn't listed here fails loudly instead of being guessed at:
PRAGMA and sqlite_master go through `src.db.table_columns` / `src.db.has_table`.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Iterator, Sequence
from typing import Any


class Row:
    """A result row readable by position or column name, like sqlite3.Row."""

    __slots__ = ("_index", "_values")

    def __init__(self, index: dict[str, int], values: Sequence[Any]) -> None:
        self._index = index
        self._values = tuple(values)

    def __getitem__(self, key: int | slice | str) -> Any:
        if isinstance(key, str):
            return self._values[self._index[key]]
        return self._values[key]

    def keys(self) -> list[str]:
        return list(self._index)

    def __iter__(self) -> Iterator[Any]:
        return iter(self._values)

    def __len__(self) -> int:
        return len(self._values)

    def __eq__(self, other: object) -> bool:
        if isinstance(other, Row):
            return self._values == other._values and self._index == other._index
        return NotImplemented

    def __hash__(self) -> int:
        return hash(self._values)

    def __repr__(self) -> str:
        return f"Row({dict(zip(self._index, self._values, strict=True))!r})"


def _row_factory(cursor):
    names = [d.name for d in cursor.description] if cursor.description else []
    index = {n: i for i, n in enumerate(names)}
    return lambda values: Row(index, values)


_SQLITE_ONLY = re.compile(r"\bPRAGMA\b|\bsqlite_master\b", re.IGNORECASE)
_OR_IGNORE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b", re.IGNORECASE)
_DDL = re.compile(r"^\s*(CREATE|ALTER)\b", re.IGNORECASE)
_DDL_TYPES = [
    (re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.IGNORECASE),
     "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bINTEGER\b", re.IGNORECASE), "BIGINT"),
    (re.compile(r"\bREAL\b", re.IGNORECASE), "DOUBLE PRECISION"),
]


def _outside_quotes(sql: str) -> Iterator[tuple[str, bool]]:
    """Split SQL into (text, quoted) pieces, so rewrites never touch string literals."""
    i, start, n = 0, 0, len(sql)
    while i < n:
        q = sql[i]
        if q in "'\"":
            if start < i:
                yield sql[start:i], False
            j = i + 1
            while j < n:
                if sql[j] == q:
                    if j + 1 < n and sql[j + 1] == q:  # '' is an escaped quote
                        j += 2
                        continue
                    break
                j += 1
            yield sql[i:j + 1], True
            i = start = j + 1
            continue
        i += 1
    if start < n:
        yield sql[start:], False


_PLACEHOLDER = re.compile(r"\?|(?<!:):([A-Za-z_]\w*)|%")


def translate(sql: str, *, has_params: bool = True) -> str:
    """SQLite-flavoured SQL as Postgres takes it."""
    if _SQLITE_ONLY.search(sql):
        raise NotImplementedError(
            "PRAGMA/sqlite_master don't exist in Postgres; use src.db.table_columns/has_table")
    out = []
    for text, quoted in _outside_quotes(sql):
        if quoted:
            out.append(text.replace("%", "%%") if has_params else text)
            continue
        if has_params:
            text = _PLACEHOLDER.sub(
                lambda m: "%s" if m[0] == "?" else "%%" if m[0] == "%" else f"%({m[1]})s", text)
        text = re.sub(r"\bchar\(", "chr(", text, flags=re.IGNORECASE)
        out.append(text)
    sql = "".join(out)
    if _OR_IGNORE.match(sql):
        sql = _OR_IGNORE.sub("INSERT INTO", sql, count=1).rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    if _DDL.match(sql):
        for pattern, repl in _DDL_TYPES:
            sql = pattern.sub(repl, sql)
    return sql


def _clean(value: Any) -> Any:
    # Postgres text can't hold NUL characters (SQLite can); scraped text occasionally has them.
    return value.replace("\x00", "") if isinstance(value, str) else value


def _params(params: Any) -> Any:
    if params is None:
        return None
    if isinstance(params, dict):
        return {k: _clean(v) for k, v in params.items()}
    return [_clean(v) for v in params]


def split_script(script: str) -> list[str]:
    """The statements of a SCHEMA script (no semicolons inside these scripts' literals)."""
    return [s.strip() for s in script.split(";") if s.strip()]


class PgConnection:
    """A psycopg connection that answers the calls the code makes on sqlite3 connections."""

    backend = "postgres"

    def __init__(self, pg) -> None:
        self._pg = pg
        self.row_factory = None  # set by callers written for sqlite3; rows are always Row here

    @property
    def raw(self):
        return self._pg

    def execute(self, sql: str, params: Any = None):
        has = params is not None and len(params) > 0
        cur = self._pg.cursor(row_factory=_row_factory)
        cur.execute(translate(sql, has_params=has), _params(params) if has else None)
        return cur

    def executemany(self, sql: str, seq: Iterable[Any]):
        rows = [_params(p) for p in seq]
        cur = self._pg.cursor(row_factory=_row_factory)
        if rows:
            cur.executemany(translate(sql), rows)
        return cur

    def executescript(self, script: str) -> None:
        for stmt in split_script(script):
            self.execute(stmt)
        self.commit()

    def commit(self) -> None:
        self._pg.commit()

    def rollback(self) -> None:
        self._pg.rollback()

    def close(self) -> None:
        self._pg.close()

    def __enter__(self) -> PgConnection:
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        # sqlite3's `with conn:` commits or rolls back and leaves the connection open.
        if exc_type is None:
            self.commit()
        else:
            self.rollback()


class KeptConnection(PgConnection):
    """One connection reused across the dashboard's requests (connecting to Azure takes
    about 0.4 s): close() only ends the transaction, as closing a sqlite3 connection would."""

    def close(self) -> None:
        if not self._pg.closed:
            self._pg.rollback()

    def alive(self) -> bool:
        if self._pg.closed or self._pg.broken:
            return False
        try:
            self._pg.execute("SELECT 1")
            self._pg.rollback()
            return True
        except Exception:  # noqa: BLE001 - a dropped connection is replaced, whatever the error
            return False
